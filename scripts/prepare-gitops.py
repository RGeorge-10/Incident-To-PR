#!/usr/bin/env python3
"""Generate the GitOps directory that Argo CD and the policy gate expect.

    python scripts/prepare-gitops.py [output-dir]      (default: lab/gitops/online-boutique)

It splits the vendored Online Boutique release manifest into one single-document file per
Deployment (`<name>.yaml`, the only files the infrastructure policy lets a proposal touch) plus
`base.yaml` for every other object, and writes a self-contained `kustomization.yaml`.
Copy the output into `deploy/online-boutique/` of your GitOps repository (or your fork).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "lab" / "vendor" / "online-boutique-v0.10.7" / "kubernetes-manifests.yaml"
HEADER = "# Generated by scripts/prepare-gitops.py from Online Boutique v0.10.7 (Apache-2.0). See lab/vendor for the license.\n"


def main() -> int:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "lab" / "gitops" / "online-boutique"
    output.mkdir(parents=True, exist_ok=True)
    documents = [doc.strip("\n") for doc in re.split(r"(?m)^---\s*$", SOURCE.read_text(encoding="utf-8"))]
    deployments: dict[str, str] = {}
    others: list[str] = []
    for doc in documents:
        body = "\n".join(line for line in doc.splitlines() if not line.lstrip().startswith("#")).strip()
        if not body:
            continue
        kind = re.search(r"(?m)^kind:\s*(\S+)", body)
        name = re.search(r"(?m)^metadata:\s*\n(?:\s+.*\n)*?\s+name:\s*(\S+)", body + "\n")
        if kind and kind.group(1) == "Deployment" and name:
            text = body if re.search(r"(?m)^  replicas:", body) else body.replace("\nspec:\n", "\nspec:\n  replicas: 1\n", 1)
            deployments[name.group(1)] = text
        else:
            others.append(body)
    for stale in output.glob("*.yaml"):
        stale.unlink()
    for name, text in deployments.items():
        (output / f"{name}.yaml").write_text(HEADER + text + "\n", encoding="utf-8")
    (output / "base.yaml").write_text(HEADER + "\n---\n".join(others) + "\n", encoding="utf-8")
    resources = "\n".join(f"  - {name}.yaml" for name in ["base", *sorted(deployments)])
    (output / "kustomization.yaml").write_text(
        HEADER + "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nnamespace: online-boutique\n"
        f"resources:\n{resources}\npatches:\n  - target:\n      version: v1\n      kind: Service\n      name: frontend\n"
        "    patch: |-\n      - op: replace\n        path: /spec/type\n        value: NodePort\n"
        "      - op: add\n        path: /spec/ports/0/nodePort\n        value: 30080\n", encoding="utf-8")
    print(f"Wrote {len(deployments)} Deployment files, base.yaml and kustomization.yaml to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
